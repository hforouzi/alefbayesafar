    public function getRolePermission($id)
    {
        return $this->createQueryBuilder('r')
            ->select('r.id, r.name, p.id as permission_id, p.name as permission_name, p.route as permission_route')
            ->leftJoin('r.permissions', 'p')
            ->andWhere('r.id = :val')
            ->setParameter('val', $id)
            ->orderBy('p.name', 'ASC')
            ->getQuery()
            ->getArrayResult();
    }
